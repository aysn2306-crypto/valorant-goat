"""Write Remotion data modules from the draft scores (video/src/data/*.ts)."""
import json, os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = pd.read_csv(os.path.join(ROOT, "data", "csv", "draft_scores.csv"), index_col=0)
REGION_COLOR = {"LCK": "#22D3EE", "LPL": "#FF5A5F", "LEC": "#F59E0B", "LCS": "#A78BFA", "LMS": "#34D399"}


def main_region(r):
    r = str(r) if isinstance(r, str) else ""
    for k in ["LCK", "LPL", "LEC", "LCS", "LMS"]:
        if k in r.split("/")[0:1] or r.startswith(k):
            return k
    return "LCK"


def trophies():
    d = P[P.c_trophies >= 10].sort_values("c_trophies", ascending=False)
    rows = []
    for i, (link, p) in enumerate(d.iterrows()):
        reg = main_region(p.regions)
        rows.append({"id": f"p{i + 1}", "name": p["name"], "team": reg, "teamColor": REGION_COLOR[reg],
                     "score": round(float(p.c_trophies), 1)})
    top5 = rows[:5]
    key = {}
    for r, (link, p) in zip(top5, d.head(5).iterrows()):
        bits = [f"{int(p.worlds_titles)} Worlds", f"{int(p.msi_titles)} MSI", f"{int(p.domestic_titles)} domestic"]
        if int(p.mvps):
            bits.append(f"{int(p.mvps)} MVP" + ("s" if int(p.mvps) > 1 else ""))
        key[r["id"]] = " · ".join(bits)
    med = float(d.c_trophies.median())
    src = ["// GENERATED by scoring/export_video.py from data/csv/draft_scores.csv. DRAFT numbers (test 4).",
           "export type FieldPlayer = { id: string; name: string; team: string; teamColor: string; score: number };",
           f"export const FIELD: FieldPlayer[] = {json.dumps(rows, ensure_ascii=False)};",
           "export const TOP5: FieldPlayer[] = FIELD.slice(0, 5);",
           f"export const KEY_STAT: Record<string, string> = {json.dumps(key, ensure_ascii=False)};",
           f"export const MEDIAN = {med:.1f};",
           f"export const POOL = {len(P)};"]
    out = os.path.join(ROOT, "video", "src", "data", "trophies.ts")
    open(out, "w").write("\n".join(src) + "\n")
    print(out, len(rows), "players; top5", [r["name"] for r in top5], key)


if __name__ == "__main__":
    trophies()
